import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { toast } from 'sonner';
import UtcToIstConverter from '@/components/UtcToIstConverter';

vi.mock('sonner', () => ({ toast: { success: vi.fn(), error: vi.fn() } }));
beforeEach(() => { vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-10-23T20:00:45Z')); });
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.useRealTimers(); });
const toggle = () => screen.getByRole('button', { name: 'UTC → IST converter' });
const input = () => screen.getByLabelText('UTC time', { exact: true });
const copy = () => screen.getByRole('button', { name: 'Copy IST time' });

describe('paste-first UTC converter', () => {
  it('starts collapsed, converts typed/pasted text immediately and preserves input through Escape/toggle', async () => {
    render(<UtcToIstConverter />);
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    fireEvent.click(toggle());
    expect(copy()).toBeDisabled();
    fireEvent.change(input(), { target: { value: '11:19:36 AM' } });
    expect(screen.getByRole('status')).toHaveTextContent('4:49:36 PM IST');
    expect(screen.getByRole('status')).toHaveTextContent('Oct 23, 2026');
    fireEvent.keyDown(input(), { key: 'Escape' });
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument());
    await waitFor(() => expect(toggle()).toHaveFocus());
    fireEvent.click(toggle());
    expect(input()).toHaveValue('11:19:36 AM');
    fireEvent.click(toggle());
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
  });
  it('shows rollover and seconds for current UTC; rejects invalid input and clears stale results', () => {
    render(<UtcToIstConverter />);
    fireEvent.click(toggle());
    fireEvent.click(screen.getByRole('button', { name: 'Use Current UTC Time' }));
    expect(input()).toHaveValue('20:00:45');
    expect(screen.getByRole('status')).toHaveTextContent('Oct 24, 2026');
    expect(screen.getByRole('status')).toHaveTextContent('1:30:45 AM IST');
    expect(screen.getByText('Next day')).toBeVisible();
    fireEvent.change(input(), { target: { value: '13:60:70 PM' } });
    expect(input()).toHaveAttribute('aria-invalid', 'true');
    expect(copy()).toBeDisabled();
    expect(screen.getByRole('status')).toHaveTextContent('—');
    fireEvent.change(input(), { target: { value: '' } });
    expect(input()).toHaveAttribute('aria-invalid', 'false');
    expect(copy()).toBeDisabled();
  });
  it('copies time or full date/time and reports clipboard failures', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined);
    vi.stubGlobal('navigator', Object.assign(Object.create(navigator), { clipboard: { writeText } }));
    render(<UtcToIstConverter />);
    fireEvent.click(toggle());
    fireEvent.change(input(), { target: { value: '11:19:36 AM' } });
    fireEvent.click(copy());
    await waitFor(() => expect(toast.success).toHaveBeenCalledWith('IST time copied'));
    expect(writeText).toHaveBeenLastCalledWith('4:49:36 PM IST');
    fireEvent.click(screen.getByRole('button', { name: 'Copy date & time' }));
    await waitFor(() => expect(writeText).toHaveBeenLastCalledWith('Oct 23, 2026 · 4:49:36 PM IST'));
    writeText.mockRejectedValueOnce(new Error('Permission denied'));
    fireEvent.click(copy());
    await waitFor(() => expect(toast.error).toHaveBeenCalledWith(expect.stringContaining('Could not copy')));
  });
  it('selects a calendar date, edits seconds and AM/PM, and returns with accurate output', () => {
    render(<UtcToIstConverter />);
    fireEvent.click(toggle());
    fireEvent.change(input(), { target: { value: '11:19:36 AM' } });
    fireEvent.click(screen.getByRole('button', { name: 'Choose UTC date' }));
    fireEvent.click(screen.getByRole('gridcell', { name: '31' }));
    expect(screen.getByText('Set Time · UTC')).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Toggle UTC AM/PM' }));
    fireEvent.click(screen.getByRole('button', { name: 'Increase UTC second' }));
    fireEvent.click(screen.getByRole('button', { name: 'Done' }));
    expect(input()).toHaveValue('11:19:37 PM');
    expect(screen.getByRole('status')).toHaveTextContent('Nov 1, 2026');
    expect(screen.getByRole('status')).toHaveTextContent('4:49:37 AM IST');
  });
  it('supports Now/Yesterday/Clear without coercing blank time units to zero', () => {
    render(<UtcToIstConverter />);
    fireEvent.click(toggle());
    fireEvent.click(screen.getByRole('button', { name: 'Choose UTC date' }));
    fireEvent.click(screen.getByRole('button', { name: 'Now' }));
    expect(screen.getByLabelText('UTC second')).toHaveValue('45');
    fireEvent.change(screen.getByLabelText('UTC second'), { target: { value: '' } });
    expect(screen.getByRole('button', { name: 'Done' })).toBeDisabled();
    fireEvent.change(screen.getByLabelText('UTC second'), { target: { value: '60' } });
    expect(screen.getByRole('button', { name: 'Done' })).toBeDisabled();
    fireEvent.change(screen.getByLabelText('UTC second'), { target: { value: '59' } });
    fireEvent.click(screen.getByRole('button', { name: 'Increase UTC second' }));
    expect(screen.getByLabelText('UTC second')).toHaveValue('00');
    fireEvent.click(screen.getByRole('button', { name: 'Back to UTC calendar' }));
    fireEvent.click(screen.getByRole('button', { name: 'Yesterday' }));
    fireEvent.click(screen.getByRole('button', { name: 'Done' }));
    expect(screen.getByRole('button', { name: 'Choose UTC date' })).toHaveTextContent('Oct 22, 2026');
    fireEvent.click(screen.getByRole('button', { name: 'Choose UTC date' }));
    fireEvent.click(screen.getByRole('button', { name: 'Clear' }));
    expect(copy()).toBeDisabled();
    expect(screen.getByText('Choose a UTC date to convert.')).toBeVisible();
  });
  it('does not submit or bubble panel actions into an unrelated form', () => {
    const submit = vi.fn(e => e.preventDefault());
    render(<form onSubmit={submit}><input aria-label="Trade draft" defaultValue="2601" /><UtcToIstConverter /></form>);
    fireEvent.click(toggle());
    fireEvent.click(screen.getByRole('button', { name: 'Use Current UTC Time' }));
    expect(screen.getByLabelText('Trade draft')).toHaveValue('2601');
    expect(submit).not.toHaveBeenCalled();
  });
});
